from concurrent.futures import ThreadPoolExecutor
from uuid import uuid4

import pytest
from sqlalchemy import delete, event, func, select
from sqlalchemy.exc import SQLAlchemyError
from sqlalchemy.orm import Session

from support_engine.database import Event, Run
from support_engine.repository import save_event
from support_engine.schemas import SupportEvent
from support_engine.simulator import build_event

pytestmark = pytest.mark.database


def test_failed_run_insert_rolls_back_the_event(db_sessions):
    payload = SupportEvent.model_validate(build_event("Hello", "customer_17"))
    with db_sessions() as session:

        def fail_run_insert(session, flush_context, instances):
            if any(isinstance(row, Run) for row in session.new):
                raise SQLAlchemyError("injected run insert failure")

        event.listen(session, "before_flush", fail_run_insert)
        with pytest.raises(SQLAlchemyError, match="run insert failure"):
            save_event(session, "rollback-test", payload)
        assert session.scalar(select(Event).where(Event.event_id == payload.event_id)) is None


def test_simultaneous_duplicates_create_one_event_and_run(db_engine):
    payload = SupportEvent.model_validate(build_event("Hello", "customer_17"))
    sender = "test-" + uuid4().hex

    def submit(_):
        with Session(db_engine) as session:
            return save_event(session, sender, payload)

    try:
        with ThreadPoolExecutor(max_workers=4) as pool:
            receipts = list(pool.map(submit, range(4)))
        assert len({receipt.run_id for receipt in receipts}) == 1
        with Session(db_engine) as session:
            saved = session.scalar(select(Event).where(Event.sender_key_id == sender))
            assert saved.payload == payload.model_dump(mode="json")
            assert (
                session.scalar(
                    select(func.count()).select_from(Event).where(Event.sender_key_id == sender)
                )
                == 1
            )
            assert (
                session.scalar(
                    select(func.count()).select_from(Run).where(Run.event_id == saved.id)
                )
                == 1
            )
    finally:
        # Delete only rows generated by this test, including after an assertion failure.
        with db_engine.begin() as connection:
            ids = select(Event.id).where(Event.sender_key_id == sender)
            connection.execute(delete(Run).where(Run.event_id.in_(ids)))
            connection.execute(delete(Event).where(Event.sender_key_id == sender))


def test_event_identity_is_scoped_to_the_verified_sender(db_sessions):
    payload = SupportEvent.model_validate(build_event("Hello", "customer_17"))
    with db_sessions() as session:
        first = save_event(session, "sender-a", payload)
        second = save_event(session, "sender-b", payload)
        assert first.run_id != second.run_id
